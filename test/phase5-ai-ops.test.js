/**
 * Test Suite: SPEC-008 Phase 5 — Module M12 AI Operations & Gate G8 Release Governance
 * 
 * Validates:
 * - Cross-module recovery gap observation & proposal generation (FR-008-014)
 * - Compound infrastructure-essential service bottleneck escalations (FR-008-015)
 * - Compute token and donor cost budget monitoring against daily cap (SPEC-008 §10 / FR-008-017)
 * - Gate G8 Production Release Approval with primary + deputy succession governance (§11)
 */

const { describe, it, before, after } = require('node:test');
const assert = require('node:assert/strict');
const { pool } = require('../src/db');
const { app } = require('../src/app');

let server;
let baseUrl;

before(async () => {
    await new Promise((resolve) => {
        server = app.listen(0, () => {
            const port = server.address().port;
            baseUrl = `http://127.0.0.1:${port}`;
            resolve();
        });
    });
});

after(async () => {
    if (server) {
        await new Promise(resolve => server.close(resolve));
    }
});

describe('SPEC-008 Phase 5 — Module M12 AI Operations & Gate G8 Release Governance', () => {
    let testNeedId = null;
    let testPledgeId = null;

    before(async () => {
        // Create an unmet recovery need in DRINKING_WATER
        const needRes = await pool.query(`
            INSERT INTO recovery_need (
                event_id, category, location, affected_population, severity, narrative, status, verification_state, is_seed
            ) VALUES (
                'EVENT-NP-TIBET-2026', 'DRINKING_WATER',
                '{"communityId": "comm-rasuwa-dhunche", "district": "Rasuwa"}'::jsonb,
                120, 'HIGH', 'Urgent need for gravity water pipe fittings in Dhunche Ward 6.',
                'VERIFIED', 'VERIFIED', TRUE
            ) RETURNING need_id
        `);
        testNeedId = needRes.rows[0].need_id;

        // Ensure an unallocated funding pledge exists
        const plgRes = await pool.query(`
            INSERT INTO funding_pledge (
                pledge_reference, event_id, donor_name, pledge_type, currency, amount_declared, amount_allocated,
                target_sector, verification_status, status, is_seed
            ) VALUES (
                'PLG-P5-TEST-WATER', 'EVENT-NP-TIBET-2026', 'Global Water Aid Consortium', 'INGO', 'USD',
                100000.00, 20000.00, 'DRINKING_WATER', 'OFFICIAL_CONFIRMED', 'COMMITTED', TRUE
            ) ON CONFLICT (pledge_reference) DO UPDATE SET amount_allocated = EXCLUDED.amount_allocated
            RETURNING pledge_id
        `);
        testPledgeId = plgRes.rows[0].pledge_id;
    });

    // ───────────────────────────────────────────────────────────
    // 1. Module M12: Continuous Observation & Gap Detection
    // ───────────────────────────────────────────────────────────
    describe('Module M12 — AI Continuous Observation & Gap Detection', () => {
        it('POST /api/v1/ops/observe-gaps runs observation cycle matching unmet needs to funding', async () => {
            const res = await fetch(`${baseUrl}/api/v1/ops/observe-gaps`, {
                method: 'POST',
                headers: {
                    'Content-Type': 'application/json',
                    'X-Debug-Actor-Class': 'AUTHORITY',
                    'X-Debug-Actor-Id': 'ops-director-1',
                    'X-Debug-IAL': 'IAL-2'
                },
                body: JSON.stringify({
                    eventId: 'EVENT-NP-TIBET-2026'
                })
            });

            assert.equal(res.status, 200);
            const data = await res.json();
            assert.ok(data.proposalsGenerated || data.proposalsConsolidated);
            assert.ok(data.tokensUsed > 0);
            assert.ok(data.costUsd > 0);

            // Verify proposal was created or consolidated
            const propRes = await pool.query(
                "SELECT * FROM ai_proposal WHERE affected_capability = 'platform_workflow' AND agent_id = 'A16-OPS'"
            );
            assert.ok(propRes.rows.length >= 1);
            assert.equal(propRes.rows[0].impact_class, 'L2');
            assert.equal(propRes.rows[0].human_decision_owner, 'COORDINATOR');
        });

        it('POST /api/v1/ops/observe-gaps triggers L3 escalation for compound infrastructure bottlenecks', async () => {
            // Check escalations generated by observation cycle
            const escRes = await pool.query(
                "SELECT * FROM escalation WHERE trigger LIKE 'COMPOUND_ISOLATION_%' AND impact_class = 'L3' ORDER BY created_at DESC"
            );
            assert.ok(escRes.rows.length >= 1, 'Compound isolation escalation must be recorded');
            const esc = escRes.rows[0];
            assert.ok(esc.trigger.startsWith('COMPOUND_ISOLATION_'));
            assert.equal(esc.assigned_reviewer, 'DISASTER_LOGISTICS_COMMAND');
            assert.ok(esc.sla_target);
        });

        it('GET /api/v1/ops/gaps-summary returns multi-module operational recovery health', async () => {
            const res = await fetch(`${baseUrl}/api/v1/ops/gaps-summary?eventId=EVENT-NP-TIBET-2026`);
            assert.equal(res.status, 200);
            const data = await res.json();
            assert.equal(data.eventId, 'EVENT-NP-TIBET-2026');
            assert.ok(Array.isArray(data.needsBreakdown));
            assert.ok(Array.isArray(data.infrastructureBreakdown));
            assert.ok(Array.isArray(data.essentialServicesBreakdown));
            assert.ok(data.fundingTotals);
            assert.ok(data.aiGovernance.pendingProposalsCount >= 0);
        });
    });

    // ───────────────────────────────────────────────────────────
    // 2. Agent Cost & Compute Token Budget Monitoring
    // ───────────────────────────────────────────────────────────
    describe('Agent Cost Accounting & Donor Budget Caps (SPEC-008 §10)', () => {
        it('GET /api/v1/ops/cost-metrics tracks daily compute tokens and confirms budget solvency', async () => {
            const res = await fetch(`${baseUrl}/api/v1/ops/cost-metrics`);
            assert.equal(res.status, 200);
            const data = await res.json();
            assert.equal(data.dailyBudgetCapUsd, 50.00);
            assert.ok(data.dailyCostUsd > 0);
            assert.ok(data.dailyBudgetRemainingUsd > 0);
            assert.equal(data.isBudgetExhausted, false);
            assert.ok(Array.isArray(data.agentBreakdown));
            assert.ok(data.agentBreakdown.length >= 1);
        });
    });

    // ───────────────────────────────────────────────────────────
    // 3. Gate G8: Production Release Approval & Succession Governance
    // ───────────────────────────────────────────────────────────
    describe('Gate G8 — Production Release Approval & Succession Governance (§11)', () => {
        it('POST /api/v1/ops/release-approval rejects release missing deputy succession approver', async () => {
            const res = await fetch(`${baseUrl}/api/v1/ops/release-approval`, {
                method: 'POST',
                headers: {
                    'Content-Type': 'application/json',
                    'X-Debug-Actor-Class': 'ADMIN',
                    'X-Debug-Actor-Id': 'admin-chair',
                    'X-Debug-IAL': 'IAL-2'
                },
                body: JSON.stringify({
                    releaseVersion: 'v1.0.0-PROD-RECOVERY',
                    primaryApproverName: 'Dr. Anil Pokhrel',
                    primaryApproverRole: 'Executive Director, NDRRMA'
                    // Missing deputy succession approver
                })
            });

            assert.equal(res.status, 400);
        });

        it('POST /api/v1/ops/release-approval ratifies release with primary + deputy succession approver', async () => {
            const res = await fetch(`${baseUrl}/api/v1/ops/release-approval`, {
                method: 'POST',
                headers: {
                    'Content-Type': 'application/json',
                    'X-Debug-Actor-Class': 'ADMIN',
                    'X-Debug-Actor-Id': 'admin-chief',
                    'X-Debug-IAL': 'IAL-2'
                },
                body: JSON.stringify({
                    releaseVersion: 'v1.0.0-PROD-RECOVERY-FINAL',
                    primaryApproverName: 'Dr. Anil Pokhrel',
                    primaryApproverRole: 'Executive Director, NDRRMA',
                    deputyApproverName: 'Suresh Adhikari',
                    deputyApproverRole: 'Joint Secretary / Deputy Disaster Relief Coordinator, MoHA',
                    releaseNotes: 'All 12 SPEC-008 modules, Gate G0 auth, Gate G2a compliance, Gate G7 i18n/offline verified.'
                })
            });

            assert.equal(res.status, 201);
            const data = await res.json();
            assert.ok(data.certification);
            assert.equal(data.certification.decision, 'APPROVED');
            assert.equal(data.certification.primaryApprover.name, 'Dr. Anil Pokhrel');
            assert.equal(data.certification.deputySuccessionApprover.name, 'Suresh Adhikari');
            assert.equal(data.certification.gatesVerified.gateG0_AuthSecurity, true);
            assert.equal(data.certification.gatesVerified.gateG2a_FundingCompliance, true);
            assert.equal(data.certification.gatesVerified.gateG7_FrontendI18nOffline, true);
            assert.equal(data.certification.gatesVerified.all12ModulesOperational, true);

            // Verify append-only audit event
            const auditRes = await pool.query(
                "SELECT * FROM audit_event WHERE action = 'GATE_G8_PRODUCTION_RELEASE_APPROVED'"
            );
            assert.ok(auditRes.rows.length >= 1);
        });

        it('GET /api/v1/ops/release-status retrieves latest ratified Gate G8 release state', async () => {
            const res = await fetch(`${baseUrl}/api/v1/ops/release-status`);
            assert.equal(res.status, 200);
            const data = await res.json();
            assert.equal(data.decision, 'APPROVED');
            assert.equal(data.primaryApprover.name, 'Dr. Anil Pokhrel');
            assert.equal(data.deputyApprover.name, 'Suresh Adhikari');
        });
    });
});
